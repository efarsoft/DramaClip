def card_of(arc_id: str) -> ArcCard | None:
    """按 id 取母题卡；未知 id（旧库方案 / 桩环境）回 None，调用方跳过注入。"""
    return _ARCS.get(arc_id)


def ids() -> tuple[str, ...]:
    return tuple(_ARCS)


def menu_line() -> str:
    """选题提示词里的母题菜单：逐张列出，附一句话本质。"""
    return "；".join(
        f"{card.name}({card.arc_id})：{card.essence}" for card in _ARCS.values()
    )
